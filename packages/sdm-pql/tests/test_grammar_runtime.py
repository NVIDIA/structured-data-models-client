"""The generated parser and the pinned ANTLR runtime must agree.

The generated parser calls `checkVersion` with the version of the tool that
produced it. A runtime whose version differs warns on every parse, so bumping
the pin without regenerating, or regenerating with a different tool, has to
fail here rather than in a user's console.
"""

import re
from importlib.metadata import version
from pathlib import Path

import pytest
import tomllib

_GRAMMAR = Path(__file__).resolve().parents[1] / (
    'src/predictive_query/grammar'
)
_PYPROJECT = Path(__file__).resolve().parents[1] / 'pyproject.toml'
_GENERATED = (
    'PQLGrammarLexer.py',
    'PQLGrammarParser.py',
    'PQLGrammarVisitor.py',
)


def _pinned_runtime() -> str:
    with _PYPROJECT.open('rb') as handle:
        config = tomllib.load(handle)
    for requirement in config['project']['dependencies']:
        match = re.fullmatch(r'antlr4-python3-runtime==(.+)', requirement)
        if match:
            return match.group(1)
    pytest.fail('pyproject does not pin antlr4-python3-runtime to one version')


def test_generated_parser_matches_the_pinned_runtime():
    pinned = _pinned_runtime()
    for name in _GENERATED:
        source = (_GRAMMAR / name).read_text()
        stamp = re.search(r'# Generated from \S+ by ANTLR (\S+)', source)
        assert stamp, f'{name} carries no generator stamp'
        assert stamp.group(1) == pinned, (
            f'{name} was generated by ANTLR {stamp.group(1)} but the runtime '
            f'is pinned to {pinned}; regenerate the grammar'
        )


def test_the_installed_runtime_is_the_pinned_one():
    assert version('antlr4-python3-runtime') == _pinned_runtime()


def test_the_parser_asserts_the_pinned_version_at_runtime():
    checked = set()
    for name in _GENERATED:
        source = (_GRAMMAR / name).read_text()
        checked.update(re.findall(r'self\.checkVersion\("(.+?)"\)', source))
    assert checked == {_pinned_runtime()}
