r"""Stable identifiers for every diagnostic this package can produce.

The code is the contract. A caller branches on ``diagnostic.code``; the message
is prose for a human and may be reworded in any release. Reading a message with
``in`` or a regex is reading something that is allowed to change.

Rules for this file:

- One code per distinguishable failure. Two call sites share a code only when
  they say the same sentence, or when one adds a further *sentence* of advice
  to it: ``... has data type {}.`` and ``... has data type {}. Did you forget
  to add quotes?`` are one failure told twice. A continuation of the same
  sentence is not covered, because ``X is invalid`` and ``X is invalid in this
  context`` are two failures that happen to share a prefix.
  ``tests/test_diagnostic_codes.py`` enforces exactly this.
- Codes are added, never renamed or repurposed. Retiring one means leaving it
  unused, not giving it a new meaning.
- The prefix names the phase that raises it, so a caller can act on a family
  without enumerating its members.

===============  ==========================================================
``PQL_PARSE``    the text is not a predictive query
``PQL_SCHEMA``   the query names something the schema does not have
``PQL_TARGET``   the target clause is not a thing that can be predicted
``PQL_TASK``     the problem type, TOP K or FORECAST clause disagrees
``PQL_TIME``     a time range is missing, impossible, or leaks the future
``PQL_TYPE``     the data or semantic types do not line up
``PQL_JOIN``     the path between two tables is missing or ambiguous
``PQL_MODEL``    valid PQL that the target model cannot run
``PQL_REWRITE``  a query-to-query rewrite could not be made
``PQL_VALUE``    a literal is outside the range the language can carry
===============  ==========================================================
"""

