"""Render the runtime Unicode name-alias profiles from pinned official data.

Pass --inputs with the five NameAliases-VERSION.txt files and LICENSE-UNICODE.txt
obtained from the URLs below, then --write.
The Unicode names and assignment ages remain maintained dependencies.
Only the version-specific alias membership is generated here.
No network access or candidate import is used by this generator.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSIONS = ('13.0.0', '14.0.0', '15.0.0', '15.1.0', '16.0.0')
HASHES = (
    '985128e8c8b2540233331d9b27d897d2c23bd5bcf1d05da960befce6efc59542',
    '14b3b677d33f95c51423dce6eef4a6a28b4b160451ecedee4b91edb6745cf4a3',
    '3e39509e8fae3e5d50ba73759d0b97194501d14a9c63107a6372a46b38be18e8',
    'fbf0e640bab36e165c4da5b6a98bdd963fcb4f923b5097f26f6f7f18b9678698',
    '9953f0fcebf5ea8091c5c581e4df0e43f20d2533c84ccca7987a9bb819a896a8',
)
LICENSE_HASH = (
    'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96'
)
OUTPUT = ROOT / 'rust/crates/sdm-request/src/tabular/unicode_aliases.rs'
LICENSE = ROOT / 'rust/crates/sdm-request/data/LICENSE-UNICODE.txt'
PROVENANCE = ROOT / 'rust/crates/sdm-request/data/UNICODE-PROVENANCE.json'


def pinned(path: Path, digest: str) -> bytes:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f'input digest mismatch: {path.name}')
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inputs', type=Path, required=True)
    parser.add_argument('--write', action='store_true', required=True)
    args = parser.parse_args()
    aliases: dict[tuple[str, int], int] = {}
    inputs = []
    for bit, (version, digest) in enumerate(zip(VERSIONS, HASHES, strict=True)):
        data = pinned(args.inputs / f'NameAliases-{version}.txt', digest)
        inputs.append(
            {
                'url': f'https://www.unicode.org/Public/{version}/ucd/NameAliases.txt',
                'sha256': digest,
            }
        )
        for line in data.decode('utf-8').splitlines():
            line = line.split('#', 1)[0].strip()
            if line:
                codepoint, name, _kind = line.split(';')
                key = (name, int(codepoint, 16))
                aliases[key] = aliases.get(key, 0) | (1 << bit)
    body = [
        '// SPDX-FileCopyrightText: Copyright (c) 1991-2026 Unicode, Inc.',
        '// SPDX-License-Identifier: Unicode-3.0',
        '// Generated by scripts/rust_core/generate_direct_unicode.py. Do not edit.',
        '// Official inputs and hashes: ../../data/UNICODE-PROVENANCE.json.',
        '// The mask bits name Unicode 13, 14, 15, 15.1 and 16 respectively.',
        '#[rustfmt::skip]',
        'pub(super) const ALIASES: &[(&str, u32, u8)] = &[',
    ]
    for (name, point), mask in sorted(aliases.items()):
        body.append(f'    ({json.dumps(name)}, 0x{point:04X}, {mask}),')
    body.extend(['];', ''])
    output = '\n'.join(body).encode()
    license_data = pinned(args.inputs / 'LICENSE-UNICODE.txt', LICENSE_HASH)
    LICENSE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(output)
    LICENSE.write_bytes(license_data)
    PROVENANCE.write_text(
        json.dumps(
            {
                'generator': 'scripts/rust_core/generate_direct_unicode.py',
                'generator_sha256': hashlib.sha256(
                    Path(__file__).read_bytes()
                ).hexdigest(),
                'profiles': VERSIONS,
                'inputs': inputs,
                'license': {
                    'url': 'https://www.unicode.org/license.txt',
                    'sha256': LICENSE_HASH,
                    'spdx': 'Unicode-3.0',
                },
                'outputs': {
                    OUTPUT.relative_to(ROOT).as_posix(): hashlib.sha256(
                        output
                    ).hexdigest(),
                    LICENSE.relative_to(ROOT).as_posix(): LICENSE_HASH,
                },
            },
            indent=2,
        )
        + '\n'
    )


if __name__ == '__main__':
    main()
