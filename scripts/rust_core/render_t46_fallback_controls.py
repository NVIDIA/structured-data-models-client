"""Render the immutable native fallback JSON as one test-only Rust constant."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path('rust/crates/sdm-engine/tests/data/t46_simd_fallback_controls.json')
OUTPUT = Path('rust/crates/sdm-engine/src/index_sort/recorded.rs')
SOURCE_SHA256 = '5e619c4cb1a968c65c446b7e79acc49fb091d3e486ad105de13fc0361469f4c1'
RECEIPT_SHA256 = 'b3fa744af2117b91ff7a76b7e6ec13c7ea16d3fb5b6c0977fea93f1809889947'
PRODUCER_SHA256 = 'bc4937120808dd9a981a9e77739ae3f532f6d040ddecf9613b198a8e5111a0c5'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', required=True)
    parser.parse_args()
    payload = (ROOT / SOURCE).read_bytes()
    if hashlib.sha256(payload).hexdigest() != SOURCE_SHA256:
        raise ValueError('canonical native fallback JSON bytes changed')
    data = json.loads(payload)
    if (
        data['source_receipt_sha256'] != RECEIPT_SHA256
        or data['producer_sha256'] != PRODUCER_SHA256
        or len(data['records']) != 123
    ):
        raise ValueError('canonical native fallback provenance changed')
    if b'"#' in payload:
        raise ValueError('canonical JSON conflicts with the Rust raw delimiter')
    writer_sha256 = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    prefix = (
        '// SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES.\n'
        '// All rights reserved.\n'
        '// SPDX-License-Identifier: Apache-2.0\n\n'
        '// @generated by scripts/rust_core/render_t46_fallback_controls.py --write.\n'
        '// Do not edit; the JSON source is the sole canonical expectation.\n'
        f'// Source: {SOURCE.as_posix()}\n'
        f'// Source SHA-256: {SOURCE_SHA256}\n'
        f'// Native receipt SHA-256: {RECEIPT_SHA256}\n'
        f'// Native producer SHA-256: {PRODUCER_SHA256}\n'
        f'// Writer SHA-256: {writer_sha256}\n\n'
        '#[cfg(test)]\n'
        'pub(super) mod controls {\n'
        '    pub(in crate::index_sort) const FALLBACK_CONTROLS: &str = r#"'
    ).encode()
    rendered = prefix + payload + b'"#;\n}\n'
    (ROOT / OUTPUT).write_bytes(rendered)
    print(
        json.dumps(
            {
                'source': SOURCE.as_posix(),
                'source_sha256': SOURCE_SHA256,
                'native_receipt_sha256': RECEIPT_SHA256,
                'native_producer_sha256': PRODUCER_SHA256,
                'writer_sha256': writer_sha256,
                'output': OUTPUT.as_posix(),
                'output_sha256': hashlib.sha256(rendered).hexdigest(),
                'records': 123,
                'candidate_validation': False,
            }
        )
    )


if __name__ == '__main__':
    main()
