"""Embed recorded sort controls in test-only modules without runtime file I/O."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT / 'rust/crates/sdm-engine'
PAIRS = (
    (
        ENGINE / 'tests/data/legacy_network64_controls.json',
        ENGINE / 'src/index_sort/network64_fixture.rs',
        ('cases',),
    ),
    (
        ROOT / 'rust/testdata/temporal-stable.json',
        ENGINE / 'src/index_sort/selected/object_stable_fixture.rs',
        ('atoms', 'cases'),
    ),
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for source, target, fields in PAIRS:
        raw = source.read_bytes()
        recorded = json.loads(raw)
        # Provenance stays in the original receipt and its hash below; the
        # domain test consumes only neutral values and expected positions.
        payload = {name: recorded[name] for name in fields}
        literal = json.dumps(
            json.dumps(payload, separators=(',', ':')),
            ensure_ascii=False,
        )
        expected = (
            '// SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES.\n'
            '// All rights reserved.\n'
            '// SPDX-License-Identifier: Apache-2.0\n\n'
            '// Generated by scripts/generate_sort_test_fixtures.py; do not edit.\n'
            f'// Source: {source.relative_to(ROOT)}\n'
            f'// SHA256: {hashlib.sha256(raw).hexdigest()}\n'
            '#[rustfmt::skip]\n'
            f'pub(super) const DATA: &str = {literal};\n'
        )
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise SystemExit(f'stale generated fixture: {target}')
        else:
            target.write_text(expected)


if __name__ == '__main__':
    main()
