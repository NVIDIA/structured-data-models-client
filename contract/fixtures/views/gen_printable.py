"""Writes ``rust/crates/sdm-pql/src/printable.rs``: the code points
Python 3.12 does not print as themselves in a ``repr``
(``str.isprintable``), as ranges, generated from the interpreter that runs
this, which must be 3.12 (Unicode 15.0). Run from the repository root with
the old client's interpreter::

    ~/code/sdmc-reference/.venv/bin/python contract/fixtures/views/gen_printable.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path('rust/crates/sdm-pql/src/printable.rs')

HEADER = """\
// SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES.
// All rights reserved.
// SPDX-License-Identifier: Apache-2.0

//! Generated by `contract/fixtures/views/gen_printable.py` from Python
//! {version} (Unicode {unicode}); do not edit. The code points Python
//! does not print as themselves in a `repr` (`str.isprintable` false), as
//! inclusive ranges in order, which [`crate::float_repr`] escapes.

/// The ranges, first and last code point, of the characters Python
/// escapes.
pub(crate) const NOT_PRINTABLE: &[(u32, u32)] = &[
"""


def ranges() -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    for code in range(0x110000):
        if chr(code).isprintable():
            continue
        if found and found[-1][1] == code - 1:
            found[-1] = (found[-1][0], code)
        else:
            found.append((code, code))
    return found


def main() -> None:
    if sys.version_info[:2] != (3, 12):
        raise SystemExit('run with Python 3.12')
    lines = [
        HEADER.format(
            version='.'.join(map(str, sys.version_info[:3])),
            unicode=unicodedata.unidata_version,
        )
    ]
    lines += [f'    (0x{a:X}, 0x{b:X}),\n' for a, b in ranges()]
    lines.append('];\n')
    OUT.write_text(''.join(lines))


if __name__ == '__main__':
    main()
