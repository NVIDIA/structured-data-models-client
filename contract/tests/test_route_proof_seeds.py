"""Seeded faults for the checks of T1.19's former exit that lacked one
(T1.15, T1.19 merged into it; decisions E53(b) and H22), each made by a
real runner process, never by editing an observation in place:

- the route proof: a ``python-old`` run that loaded ``sdm_client._native``
  fails ``compare.py``'s ``route`` rule ("the old route loaded the core");
  the plain run passes;
- the control: an observation regenerated by fresh ``python-core`` and
  ``python-old`` runs, whose request UUID (``metadata.request_id``) differs
  from the reference's, passes the comparator under an acceptance copy of
  ``base.regression``, where the payload rule gates; the same observation
  with another field changed, or the UUID dropped, fails it;
- H22, on the product path: the public ``materialize()`` on the core route,
  with the Python host's DuckDB provider forced, by a test-side patch of
  the provider and no production hook, to bind the core's ``neighbors``
  key sets through float64, gives a payload the comparator fails, where
  the unforced core route matches the old route.

Why H22's seed uses int64 keys past 2**53 and not decimals: a decimal key
reaches no key set on the product path today. The reference refuses
decimal keys at ``materialize`` (``key.decimal-18-0``, ``key.decimal-38-10``
and ``key.hugeint`` expect ``INTERNAL_ERROR``), those cases run only
``describe_source`` on the core, and the core route's ``materialize``
takes integer and text keys. Integers past 2**53 collide as float64 just
as the decimals did, so forcing them through float64 is the same
mis-keying on a path the product runs. The binding-level seeds that force
decimal keys themselves are ``sdm-testkit``'s
``tests/duckdb_provider.rs::keys_that_collide_as_float64_bind_join_and_answer_exactly``
and its Python twin in ``tests_test_ops/test_the_duckdb_provider.py``.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
RUNNERS = ROOT / 'contract/runners'
RUN_PYTHON = RUNNERS / 'run_python.py'
CASES = ROOT / 'contract/cases'
REFERENCE = next((ROOT / 'contract/reference').glob('*.jsonl'))
ACCEPTED = CASES / 's0/s0.accept.sum-window.json'
REGRESSION = CASES / 's1/base.regression.json'
#: The first integer float64 cannot tell from its successor.
SHIFT = 2**53


def _module(name: str, path: Path) -> ModuleType:
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


run_python = _module('run_python', RUN_PYTHON)
compare = _module('compare', ROOT / 'scripts/rust_core/compare.py')


def _runner(tmp_path: Path, prelude: str) -> Path:
    r"""``run_python.py``, run after ``prelude`` in the same process: the
    test's own patch, outside the product."""
    script = tmp_path / 'patched_runner.py'
    script.write_text(
        'import runpy\nimport sys\n'
        + prelude
        + f'\nsys.path.insert(0, {str(RUNNERS)!r})\n'
        + f'sys.argv = [{str(RUN_PYTHON)!r}, *sys.argv[1:]]\n'
        + "runpy.run_path(sys.argv[0], run_name='__main__')\n",
        encoding='utf-8',
    )
    return script


def _run(
    mode: str, out: Path, cases: Path, script: Path = RUN_PYTHON
) -> list[dict[str, Any]]:
    done = subprocess.run(
        [
            sys.executable,
            '-I',
            str(script),
            '--mode',
            mode,
            '--out',
            str(out),
            str(cases),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert done.returncode == 0, done.stderr
    return [json.loads(x) for x in out.read_text().splitlines()]


def _write(path: Path, lines: list[dict[str, Any]]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(''.join(json.dumps(x) + '\n' for x in lines))
    return path


def _reference(case: str, digest: str | None = None) -> dict[str, Any]:
    for line in REFERENCE.read_text().splitlines():
        observation: dict[str, Any] = json.loads(line)
        if observation['case'] == case:
            if digest is not None:
                observation['identity']['inputs']['case'] = digest
            return observation
    raise AssertionError(f'no reference observation of {case}')


def _rules(report: Any) -> set[str | None]:
    return {rule for rule, _ in report.failures}


def _acceptance_copy(
    tmp_path: Path, source: Path, change: Any = None
) -> tuple[Path, str]:
    r"""An acceptance copy of a case, alone in a directory, so the
    comparator gates every rule on it; with its file's digest."""
    case = json.loads(source.read_text())
    case['status'] = 'acceptance'
    if change is not None:
        change(case)
    cases = tmp_path / 'cases'
    cases.mkdir(exist_ok=True)
    written = cases / f'{case["id"]}.json'
    written.write_text(json.dumps(case, indent=1), encoding='utf-8')
    return cases, run_python.digest(written.read_bytes())


# --- the route proof: python-old with the core loaded ------------------------


def test_a_python_old_run_that_loaded_the_core_fails_the_route_rule(
    tmp_path: Path,
) -> None:
    reference = _write(
        tmp_path / 'python-ref.jsonl', [_reference('s0.accept.sum-window')]
    )
    plain = _run('python-old', tmp_path / 'python-old.jsonl', ACCEPTED)
    assert plain[0]['identity']['native_loaded'] is False
    report = compare.compare(
        [ACCEPTED], reference, [tmp_path / 'python-old.jsonl']
    )
    assert report.failures == [], report.texts
    # The same runner, in a process that imported the native module first.
    loaded = tmp_path / 'loaded'
    loaded.mkdir()
    script = _runner(loaded, 'import sdm_client._native\n')
    [observation] = _run(
        'python-old', loaded / 'python-old.jsonl', ACCEPTED, script
    )
    assert observation['identity']['native_loaded'] is True
    report = compare.compare(
        [ACCEPTED], reference, [loaded / 'python-old.jsonl']
    )
    assert _rules(report) == {'route'}, report.texts
    assert (
        'route',
        's0.accept.sum-window: python-old: route: the old route loaded the core',
    ) in report.failures


# --- the control: a regenerated observation, its request UUID changed --------


def _metadata(observation: dict[str, Any]) -> dict[str, Any]:
    found: dict[str, Any] = observation['public']['payloads'][0]['parsed'][
        'metadata'
    ]
    return found


def test_a_regenerated_observation_whose_request_id_changed_passes(
    tmp_path: Path,
) -> None:
    cases, digest = _acceptance_copy(tmp_path, REGRESSION)
    reference = _reference('base.regression', digest)
    files = {}
    for runner in ('python-core', 'python-old'):
        [observation] = _run(runner, tmp_path / f'{runner}.jsonl', cases)
        assert observation['outcome']['result'] == 'success'
        files[runner] = (tmp_path / f'{runner}.jsonl', observation)
    ids = {
        'python-ref': _metadata(reference)['request_id'],
        **{
            runner: _metadata(o)['request_id']
            for runner, (_, o) in files.items()
        },
    }
    # Regenerated: each run drew a request UUID of its own.
    assert len(set(ids.values())) == 3, ids
    assert all(isinstance(x, str) and x for x in ids.values()), ids
    reference_file = _write(tmp_path / 'python-ref.jsonl', [reference])
    report = compare.compare(
        [cases], reference_file, [path for path, _ in files.values()]
    )
    assert report.failures == [], report.texts
    # Not vacuous: on the same regenerated observation, the payload rule
    # gates here, and fails another field changed or the UUID dropped.
    for fault in (
        lambda m: m.update(source_query='PREDICT x'),
        lambda m: m.pop('request_id'),
    ):
        observation = json.loads(json.dumps(files['python-core'][1]))
        fault(_metadata(observation))
        seeded = _write(
            tmp_path / 'seeded' / 'python-core.jsonl', [observation]
        )
        report = compare.compare([cases], reference_file, [seeded])
        assert 'payload' in _rules(report), report.texts


# --- H22: a forced float64 key conversion on the product path ----------------

#: The test's patch of the Python host's DuckDB provider: every key set the
#: core sends with a ``neighbors`` step is read, its ``key`` column cast to
#: float64 and back, and handed on; the distinct keys before and after are
#: recorded, so the seed is shown to collide.
FORCED = """
import json
import os
import pyarrow as pa
from sdm_client._rust.providers.duckdb import DuckDBProvider

answer = DuckDBProvider.__call__
record = os.path.join(os.path.dirname(__file__), 'collisions.jsonl')


def forced(self, step, keys=None):
    tables = {
        attachment: pa.RecordBatchReader._import_from_c_capsule(
            stream.__arrow_c_stream__()
        ).read_all()
        for attachment, stream in (keys or {}).items()
    }
    if step['request']['request'] == 'neighbors':
        for attachment, table in list(tables.items()):
            key = table.column('key')
            through = key.cast(pa.float64(), safe=False).cast(key.type, safe=False)
            with open(record, 'a') as handle:
                handle.write(json.dumps([
                    str(key.type),
                    len(set(key.to_pylist())),
                    len(set(through.to_pylist())),
                ]) + '\\n')
            tables[attachment] = table.set_column(
                table.column_names.index('key'), 'key', through
            )
    return answer(self, step, tables)


DuckDBProvider.__call__ = forced
"""


def _past_float64(case: dict[str, Any]) -> None:
    r"""``base.regression`` with every user's key moved past 2**53."""
    case['id'] = 'h22.keys-past-float64'
    case['input']['setup'] = [
        f'UPDATE users SET user_id = user_id + {SHIFT}',
        f'UPDATE orders SET user_id = user_id + {SHIFT}',
    ]
    case['input']['materialize']['indices'] = [SHIFT, SHIFT + 1]
    case['core']['materialize']['indices'] = [
        {'t': 'i64', 'v': str(SHIFT)},
        {'t': 'i64', 'v': str(SHIFT + 1)},
    ]


def _in_another_cell(path: Path) -> Path:
    r"""No reference observation exists for the case (the reference is
    recorded on the reference machine), so the comparator's comparison in
    another runtime cell is used (H1): ``python-core``'s host fields,
    payload included, against ``python-old``'s in the same cell."""
    lines = [json.loads(x) for x in path.read_text().splitlines()]
    for line in lines:
        line['identity']['cell'] = 'dbr17-pandas2'
    return _write(path.with_name(f'cell-{path.name}'), lines)


def test_a_forced_float64_key_conversion_on_the_product_path_fails(
    tmp_path: Path,
) -> None:
    cases, _ = _acceptance_copy(tmp_path, REGRESSION, _past_float64)
    _run('python-old', tmp_path / 'python-old.jsonl', cases)
    old = _in_another_cell(tmp_path / 'python-old.jsonl')
    # The control: the unforced core route is the old route's.
    [core] = _run('python-core', tmp_path / 'python-core.jsonl', cases)
    assert core['identity']['operations'] == [
        'describe_source',
        'materialize',
        'predict',
    ]
    report = compare.compare(
        [cases], None, [_in_another_cell(tmp_path / 'python-core.jsonl'), old]
    )
    assert report.failures == [], report.texts
    # The seed: the same call, its neighbors' key sets forced through
    # float64 by the patched provider.
    forced = tmp_path / 'forced'
    forced.mkdir()
    script = _runner(forced, FORCED)
    [seeded] = _run('python-core', forced / 'python-core.jsonl', cases, script)
    collisions = [
        json.loads(x)
        for x in (forced / 'collisions.jsonl').read_text().splitlines()
    ]
    # Not vacuous: the keys were int64, and collided through float64.
    assert collisions and all(kind == 'int64' for kind, _, _ in collisions)
    assert any(after < before for _, before, after in collisions), collisions
    assert seeded['outcome']['result'] == 'success'
    report = compare.compare(
        [cases], None, [_in_another_cell(forced / 'python-core.jsonl'), old]
    )
    assert 'payload' in _rules(report), report.texts
    assert any(
        rule == 'payload'
        and 'python-core against python-old: public.payloads' in text
        for rule, text in report.failures
    ), report.texts
