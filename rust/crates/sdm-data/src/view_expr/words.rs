//! The word tables of the old client's `RE/view_expr.py:318-737`, each in
//! sorted order, generated from that module so none differs by a word.
//! [`super::check`] and [`super::names`] read them through [`has`].

/// Whether the sorted table `words` holds `word`.
pub(crate) fn has(words: &[&str], word: &str) -> bool {
    words.binary_search(&word).is_ok()
}

