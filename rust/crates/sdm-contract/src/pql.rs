//! The validated-query format: a predictive query PQL accepted, resolved
//! against its schema, as the core's PQL adapter hands it to the rest of the
//! core.
//!
//! Whichever PQL implementation sits behind the adapter, the interim parser
//! now and the PQL team's crate later, gives its answer in this format, so
//! nothing past the adapter depends on the implementation. The format has a
//! version of its own, independent of the contract's: its JSON Schema is
//! generated by [`validated_query_schema_json`], committed as
//! `schema/pql-validated-query-<version>.json`, and locked by hash in
//! `schema/validated-query.lock`, under the same rules as the contract's
//! schema.
//!
//! A node is the tree the reference's validator builds: each carries the
//! data and semantic type validation inferred, the time window it and its
//! children span, and where it is in the query text.

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::ops::{ColumnRef, Dtype, Span, Stype};

/// The version of the validated-query format this build writes.
pub const VALIDATED_QUERY_VERSION: u32 = 2;

/// A query PQL accepted.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct ValidatedQuery {
    /// What the query predicts for: the entity column, or a filter over it.
    pub entity: PqlNode,
    /// What the query predicts, joined to the entity's table.
    pub target: PqlNode,
    /// The `ASSUMING` condition.
    pub assuming: Option<PqlNode>,
    /// The condition naming the entities of `FOR t.c = 1` or
    /// `FOR t.c IN (1, 2)`.
    pub entity_ids: Option<PqlNode>,
    pub problem_type: Option<ProblemType>,
    /// `RANK TOP k`: k's decimal digits, as large as the query wrote it.
    pub top_k: Option<String>,
    /// How many timeframes `FORECAST n TIMEFRAMES` asks for; 1 otherwise.
    pub num_forecasts: u32,
    pub entity_clause: EntityClause,
    /// Whether the query defines a task to train on or asks a model.
    pub mode: QueryMode,
    /// The query started with `EVALUATE`.
    pub evaluate: bool,
    /// The query started with `EXPLAIN`.
    pub explain: bool,
}

/// One node of a validated query.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PqlNode {
    /// The data type validation inferred, if any.
    pub dtype: Option<NodeType>,
    /// The semantic type validation inferred, if any.
    pub stype: Option<Stype>,
    /// The time window of this node and its children, merged.
    pub range: Option<Window>,
    /// Where the node is in the query text.
    pub span: Option<Span>,
    pub kind: NodeKind,
}

/// What a node is.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "node", rename_all = "snake_case", deny_unknown_fields)]
pub enum NodeKind {
    /// A column, or a table's wildcard column `*`.
    Column {
        column: ColumnRef,
    },
    Constant {
        literal: PqlLiteral,
    },
    /// `target op value`.
    Condition {
        target: Box<PqlNode>,
        op: ConditionOp,
        value: Box<PqlNode>,
        /// The query wrote the operator as `LIKE` or `NOT LIKE`.
        from_like: bool,
    },
    /// `left AND right`, `left OR right` or `NOT left`.
    Logical {
        op: LogicalOp,
        left: Box<PqlNode>,
        right: Option<Box<PqlNode>>,
    },
    /// `target WHERE condition`.
    Filter {
        target: Box<PqlNode>,
        condition: Box<PqlNode>,
    },
    Aggregation {
        aggregation: Aggregation,
        target: Box<PqlNode>,
        /// The window the query wrote, in the unit validation left it in.
        window: Option<Window>,
        /// The column the aggregation groups by, joined to the entity.
        group_by: Option<ColumnRef>,
        /// The time column of the aggregated table, for a windowed
        /// aggregation.
        time_column: Option<ColumnRef>,
    },
    /// `target`, reached from the entity's table through a foreign key.
    Join {
        target: Box<PqlNode>,
        lhs_key: ColumnRef,
        rhs_key: ColumnRef,
    },
}

/// A node's data type: a value's, or an array's of that element type.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "shape", content = "dtype", rename_all = "snake_case")]
pub enum NodeType {
    Value(Dtype),
    Array(Dtype),
}

/// What a constant stands for.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum PqlLiteral {
    Null,
    Bool {
        value: bool,
    },
    /// An integer's decimal digits, exactly, without leading zeros.
    Int {
        value: String,
    },
    /// A float as the query wrote it.
    Float {
        text: String,
    },
    /// A string, its escapes read.
    String {
        value: String,
    },
    /// A date literal as the query wrote it, the date and time it reads as,
    /// `YYYY-MM-DDTHH:MM:SS`, and the UTC offset in seconds when the literal
    /// gives one.
    Time {
        text: String,
        value: String,
        offset: Option<i32>,
    },
    /// An array's elements, each a constant node.
    Array {
        items: Vec<PqlNode>,
    },
}

/// A time window: `start` to `end` units from the anchor time; no `start`
/// is `-INF`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Window {
    pub start: Option<i32>,
    pub end: i32,
    pub unit: TimeUnit,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum TimeUnit {
    Seconds,
    Minutes,
    Hours,
    Days,
    Weeks,
    Months,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ConditionOp {
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
    In,
    IsIn,
    StartsWith,
    EndsWith,
    Contains,
    NotContains,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum LogicalOp {
    And,
    Or,
    Not,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Aggregation {
    Sum,
    Avg,
    Min,
    Max,
    Count,
    CountDistinct,
    First,
    Last,
    ListDistinct,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ProblemType {
    Rank,
    Classify,
    Forecast,
}

/// `FOR EACH`, or `FOR` with the entities named.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum EntityClause {
    ForEach,
    For,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum QueryMode {
    Training,
    Inference,
}

/// The JSON Schema of [`ValidatedQuery`], as committed: pretty-printed, with
/// a trailing newline.
pub fn validated_query_schema_json() -> String {
    let mut schema = schemars::schema_for!(ValidatedQuery);
    schema.insert(
        "$id".into(),
        format!("sdm-pql-validated-query/{VALIDATED_QUERY_VERSION}").into(),
    );
    let mut text = serde_json::to_string_pretty(&schema).expect("a schema serializes");
    text.push('\n');
    text
}
